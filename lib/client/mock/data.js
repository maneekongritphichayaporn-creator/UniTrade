/** รูปจำลอง: SVG เป็น data URI ไม่ต้องมีไฟล์จริงและไม่ติดไปใน production */
export function mockImageUrl(productId, index = 0) {
  const seed = [...productId].reduce((sum, char) => sum + char.charCodeAt(0), 0) + index * 37;
  const hue = seed % 360;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="600" height="600" viewBox="0 0 600 600">
<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
<stop offset="0" stop-color="hsl(${hue} 70% 92%)"/><stop offset="1" stop-color="hsl(${(hue + 40) % 360} 65% 80%)"/>
</linearGradient></defs>
<rect width="600" height="600" fill="url(#g)"/>
<g fill="none" stroke="hsl(${hue} 45% 45%)" stroke-width="18" stroke-linecap="round" stroke-linejoin="round" opacity="0.5">
<path d="M190 235h220l-26 230H216z"/><path d="M250 235v-32a50 50 0 0 1 100 0v32"/>
</g></svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}
